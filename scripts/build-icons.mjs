// Generates src/components/icons/icon-data.ts from assets/icons/icon-map.json.
// Only the mapped icons are emitted, so consumers never bundle the full set.
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = async (path) => readFile(new URL(path, root), "utf8");

const iconMap = JSON.parse(await read("assets/icons/icon-map.json"));
const listaso = JSON.parse(await read("assets/icons/listaso-icons.json"));
const gridHeight = listaso.height ?? 1024;

// IcoMoon keeps glyph names in `selection`, in the same order as `icons`.
const listasoGlyphs = new Map(
  listaso.selection.map((entry, index) => [entry.name, listaso.icons[index]]),
);

async function fromListaso(glyph) {
  const icon = listasoGlyphs.get(glyph);
  if (!icon) throw new Error(`Listaso glyph not found: ${glyph}`);
  const width = icon.width ?? gridHeight;
  return { viewBox: `0 0 ${width} ${gridHeight}`, paths: icon.paths };
}

async function fromMaterial(file) {
  const svg = await read(`assets/icons/material/${file}`);
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((match) => match[1]);
  if (!viewBox || paths.length === 0) throw new Error(`Unreadable Material SVG: ${file}`);
  return { viewBox, paths };
}

const entries = [];
for (const [name, spec] of Object.entries(iconMap)) {
  const data =
    spec.source === "listaso"
      ? await fromListaso(spec.glyph)
      : spec.source === "material"
        ? await fromMaterial(spec.file)
        : null;
  if (!data) throw new Error(`Unknown icon source for ${name}: ${spec.source}`);
  const origin = spec.glyph ?? spec.file;
  entries.push(
    `  ${JSON.stringify(name)}: {\n` +
      `    source: ${JSON.stringify(spec.source)},\n` +
      `    origin: ${JSON.stringify(origin)},\n` +
      `    viewBox: ${JSON.stringify(data.viewBox)},\n` +
      `    paths: ${JSON.stringify(data.paths)},\n` +
      `  },`,
  );
}

const output = `// Generated by scripts/build-icons.mjs from assets/icons/icon-map.json.
// Do not edit by hand: change the map and run \`pnpm icons\`.

export type IconGlyph = {
  source: "listaso" | "material";
  origin: string;
  viewBox: string;
  paths: readonly string[];
};

export const iconData = {
${entries.join("\n")}
} as const satisfies Record<string, IconGlyph>;

export type IconName = keyof typeof iconData;
`;

await writeFile(new URL("src/components/icons/icon-data.ts", root), output);
console.log(`Generated ${entries.length} icons.`);
